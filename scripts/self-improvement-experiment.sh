#!/usr/bin/env bash
# self-improvement-experiment.sh — sandboxed recursive-improvement experiment.

set -uo pipefail

LAB_DIR="${DEVIN_SELF_IMPROVE_DIR:-$HOME/workbench/self-improvement-lab}"
PROFILE_DIR="${DEVIN_SELF_IMPROVE_PROFILE_DIR:-$HOME/.bashrc.d}"
LOG_FILE="$LAB_DIR/telemetry.jsonl"
JOURNAL="$LAB_DIR/JOURNAL.md"
PROPOSALS="$LAB_DIR/PROPOSALS.md"
KILL_FILE="$LAB_DIR/KILLED"
GENERATED_DIR="$LAB_DIR/generated"
HELPERS="$GENERATED_DIR/tier1-helpers.sh"
PROFILE="$PROFILE_DIR/90-self-improvement-lab.sh"

usage() {
  cat <<'EOF'
Usage:
  self-improvement-experiment start
  self-improvement-experiment status
  self-improvement-experiment record "<task>" -- <command...>
  self-improvement-experiment analyze
  self-improvement-experiment propose
  self-improvement-experiment apply-tier1
  self-improvement-experiment kill
  self-improvement-experiment --self-test
EOF
}

init_lab() {
  mkdir -p "$LAB_DIR" "$GENERATED_DIR"
  touch "$LOG_FILE"
  if [ ! -f "$JOURNAL" ]; then
    cat > "$JOURNAL" <<EOF
# Self-Improvement Experiment Journal

Started: $(date -Iseconds)

EOF
  fi
}

journal() {
  init_lab
  printf '%s | %s\n' "$(date -Iseconds)" "$*" >> "$JOURNAL"
}

is_killed() {
  [ -f "$KILL_FILE" ]
}

require_live() {
  if is_killed; then
    echo "Experiment is killed. Run 'self-improvement-experiment start' to restart." >&2
    exit 2
  fi
}

analyze_python() {
  LOG_FILE="$LOG_FILE" python3 <<'PY'
import json
import os
from collections import Counter, defaultdict
from pathlib import Path

log_path = Path(os.environ["LOG_FILE"])
entries = []
if log_path.exists():
    for line in log_path.read_text().splitlines():
        try:
            entries.append(json.loads(line))
        except json.JSONDecodeError:
            pass

print("# Self-Improvement Analysis")
print()
print(f"Entries: {len(entries)}")
if not entries:
    print()
    print("No telemetry yet. Use `record \"task\" -- <command...>` first.")
    raise SystemExit(0)

by_task = Counter(entry["task"] for entry in entries)
by_command = Counter(entry["command"].split()[0] for entry in entries if entry.get("command"))
failures = [entry for entry in entries if entry["exit_code"] != 0]
slow = [entry for entry in entries if entry["duration_s"] > 2]
duration_by_task = defaultdict(float)
count_by_task = defaultdict(int)

for entry in entries:
    duration_by_task[entry["task"]] += entry["duration_s"]
    count_by_task[entry["task"]] += 1

print()
print("## Repeated tasks")
for task, count in by_task.most_common():
    if count < 2:
        continue
    total = duration_by_task[task]
    avg = total / count
    print(f"- {count}x `{task}` — total {total:.1f}s, avg {avg:.1f}s")

print()
print("## Repeated command families")
for command, count in by_command.most_common():
    if count < 2:
        continue
    print(f"- {count}x `{command}`")

print()
print("## Failures")
if failures:
    for entry in failures[-10:]:
        print(f"- exit {entry['exit_code']}: `{entry['task']}` → `{entry['command']}`")
else:
    print("- none")

print()
print("## Slow operations (>2s)")
if slow:
    for entry in sorted(slow, key=lambda item: item["duration_s"], reverse=True)[:10]:
        print(f"- {entry['duration_s']:.1f}s: `{entry['task']}` → `{entry['command']}`")
else:
    print("- none")
PY
}

write_proposals() {
  init_lab
  local analysis_file="$LAB_DIR/ANALYSIS.md"
  analyze_python > "$analysis_file"
  cat > "$PROPOSALS" <<EOF
# Self-Improvement Proposals

Generated: $(date -Iseconds)

## Current signal

$(cat "$analysis_file")

## Tier 1 candidates

These are reversible and may be applied with:

\`\`\`bash
self-improvement-experiment apply-tier1
\`\`\`

- Add \`si-status\`, \`si-analyze\`, and \`si-propose\` helpers for this experiment.
- Add \`wb-status\` for quick workbench branch/status checks.
- Add \`wb-lessons\` for quick review of recent lessons.

## Tier 2 candidates

Requires PR review. Promote only if telemetry shows repeated value:

- Convert high-signal helpers into documented workbench commands.
- Add a PB-4 subsection for experiment findings that recur 3+ times.
- Tighten scripts that repeatedly appear in failure telemetry.

## Tier 3 candidates

Blocked by design. Convert to PB-4 proposal only:

- New installed tools.
- Snapshot rebuilds.
- systemd or shell startup changes beyond \`~/.bashrc.d/90-self-improvement-lab.sh\`.
- Anything involving secrets or browser credentials.
EOF
  journal "proposals generated at $PROPOSALS"
  echo "Wrote $PROPOSALS"
}

apply_tier1() {
  init_lab
  require_live
  write_proposals >/dev/null
  mkdir -p "$PROFILE_DIR"
  cat > "$HELPERS" <<'EOF'
# Generated by self-improvement-experiment apply-tier1.
alias si-status='self-improvement-experiment status'
alias si-analyze='self-improvement-experiment analyze'
alias si-propose='self-improvement-experiment propose'
alias wb-status='git -C ~/workbench status --short --branch'
alias wb-lessons='tail -20 ~/workbench/LESSONS.md'
EOF
  cp "$HELPERS" "$PROFILE"
  journal "tier1 helpers applied to $PROFILE"
  echo "Applied Tier 1 helpers to $PROFILE"
}

kill_experiment() {
  init_lab
  touch "$KILL_FILE"
  if [ -f "$PROFILE" ]; then
    rm "$PROFILE"
  fi
  journal "kill switch activated; helpers disabled"
  echo "Self-improvement experiment killed. Runtime files remain in $LAB_DIR"
}

record_command() {
  init_lab
  if is_killed; then
    echo "[self-improvement] killed; running command without telemetry" >&2
  fi

  local task="${1:-}"
  if [ -z "$task" ]; then
    echo "Usage: self-improvement-experiment record \"<task>\" -- <command...>" >&2
    exit 64
  fi
  shift || true
  if [ "${1:-}" = "--" ]; then
    shift
  fi
  if [ "$#" -eq 0 ]; then
    echo "Usage: self-improvement-experiment record \"<task>\" -- <command...>" >&2
    exit 64
  fi

  local start end duration exit_code command_text
  start=$(date +%s)
  local start_iso
  start_iso=$(date -Iseconds)
  command_text="$*"

  "$@"
  exit_code=$?

  end=$(date +%s)
  duration=$((end - start))
  local end_iso
  end_iso=$(date -Iseconds)

  if ! is_killed; then
    TASK="$task" COMMAND_TEXT="$command_text" START_ISO="$start_iso" END_ISO="$end_iso" DURATION="$duration" EXIT_CODE="$exit_code" \
      python3 <<'PY' >> "$LOG_FILE"
import json
import os

print(json.dumps({
    "ts": os.environ["START_ISO"],
    "end_ts": os.environ["END_ISO"],
    "task": os.environ["TASK"],
    "command": os.environ["COMMAND_TEXT"],
    "duration_s": int(os.environ["DURATION"]),
    "exit_code": int(os.environ["EXIT_CODE"]),
}))
PY
    journal "recorded '$task' in ${duration}s exit=$exit_code"
  fi

  return "$exit_code"
}

self_test() {
  local tmp
  tmp=$(mktemp -d)
  DEVIN_SELF_IMPROVE_DIR="$tmp/lab" DEVIN_SELF_IMPROVE_PROFILE_DIR="$tmp/profile" "$0" start || { echo "FAIL: start failed" >&2; rm -rf "$tmp"; exit 1; }
  DEVIN_SELF_IMPROVE_DIR="$tmp/lab" DEVIN_SELF_IMPROVE_PROFILE_DIR="$tmp/profile" "$0" record "fast smoke" -- true || { echo "FAIL: record failed" >&2; rm -rf "$tmp"; exit 1; }
  DEVIN_SELF_IMPROVE_DIR="$tmp/lab" DEVIN_SELF_IMPROVE_PROFILE_DIR="$tmp/profile" "$0" record "fast smoke" -- true || { echo "FAIL: record failed" >&2; rm -rf "$tmp"; exit 1; }
  DEVIN_SELF_IMPROVE_DIR="$tmp/lab" DEVIN_SELF_IMPROVE_PROFILE_DIR="$tmp/profile" "$0" propose >/dev/null || { echo "FAIL: propose failed" >&2; rm -rf "$tmp"; exit 1; }
  DEVIN_SELF_IMPROVE_DIR="$tmp/lab" DEVIN_SELF_IMPROVE_PROFILE_DIR="$tmp/profile" "$0" apply-tier1 >/dev/null || { echo "FAIL: apply-tier1 failed" >&2; rm -rf "$tmp"; exit 1; }
  test -s "$tmp/lab/telemetry.jsonl" || { echo "FAIL: telemetry.jsonl empty or not found" >&2; rm -rf "$tmp"; exit 1; }
  test "$(wc -l < "$tmp/lab/telemetry.jsonl" | tr -d ' ')" -eq 2 || { echo "FAIL: expected 2 telemetry entries" >&2; rm -rf "$tmp"; exit 1; }
  test -f "$tmp/lab/PROPOSALS.md" || { echo "FAIL: PROPOSALS.md not found" >&2; rm -rf "$tmp"; exit 1; }
  test -f "$tmp/profile/90-self-improvement-lab.sh" || { echo "FAIL: profile helper not found" >&2; rm -rf "$tmp"; exit 1; }
  DEVIN_SELF_IMPROVE_DIR="$tmp/lab" DEVIN_SELF_IMPROVE_PROFILE_DIR="$tmp/profile" "$0" kill >/dev/null || { echo "FAIL: kill failed" >&2; rm -rf "$tmp"; exit 1; }
  test -f "$tmp/lab/KILLED" || { echo "FAIL: KILLED file not found" >&2; rm -rf "$tmp"; exit 1; }
  test ! -f "$tmp/profile/90-self-improvement-lab.sh" || { echo "FAIL: profile helper not removed" >&2; rm -rf "$tmp"; exit 1; }
  rm -rf "$tmp"
  echo "self-improvement-experiment self-test OK"
}

CMD="${1:-}"
shift || true

case "$CMD" in
  start)
    init_lab
    rm -f "$KILL_FILE"
    journal "experiment started"
    echo "Self-improvement experiment started at $LAB_DIR"
    ;;
  status)
    init_lab
    if is_killed; then status="killed"; else status="running"; fi
    entries=$(wc -l < "$LOG_FILE" | tr -d ' ')
    echo "Status: $status"
    echo "Lab: $LAB_DIR"
    echo "Telemetry entries: $entries"
    echo "Journal: $JOURNAL"
    echo "Proposals: $PROPOSALS"
    ;;
  record)
    record_command "$@"
    ;;
  analyze)
    init_lab
    analyze_python
    ;;
  propose)
    write_proposals
    ;;
  apply-tier1)
    apply_tier1
    ;;
  kill|stop)
    kill_experiment
    ;;
  --self-test)
    self_test
    ;;
  *)
    usage
    exit 64
    ;;
esac
